export interface StarData {
  id: string;
  name: string;
  ra: number;        // Right Ascension in decimal hours (0..24)
  dec: number;       // Declination in degrees (-90..+90)
  dist: number;      // Distance in Light Years
  spectral: string;  // Spectral classification (e.g., G2V, M5.5Ve, L7.5, Y2)
  mag: number;       // Apparent magnitude
  absMag: number;    // Absolute magnitude
  lum?: number;     // Luminosity relative to Sol (L_sun), if documented
  temp?: number;    // Surface temperature in Kelvin, if documented
  source?: string;  // Source for astrometry, spectral type and V magnitude
  mass?: number;     // Solar masses
  radius?: number;   // Solar radii
  metallicity?: number; // Metallicity [Fe/H] in dex (e.g. +0.05, -0.24)
  stellarType?: string; // Full classification (e.g., Yellow Dwarf, Red Supergiant, Brown Dwarf)
  ageGyr?: number;    // Estimated stellar age in Giga-years (Gyr)
  rotationPeriodDays?: number; // Rotation period in days
  radialVelocityKmS?: number; // Radial velocity in km/s
  properMotionMasYr?: number; // Proper motion in mas/yr
  variableType?: string; // Variable type (e.g. BY Draconis, Mira, Flare Star)
  isBrownDwarf?: boolean; // Flag for brown dwarfs (L, T, Y class)
  constellation: string;
  exoplanets?: number;
  isLocal?: boolean;
  isProminent?: boolean;
  isConstellationNode?: boolean;
  description: string;
}

